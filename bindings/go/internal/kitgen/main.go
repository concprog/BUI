// Command kitgen builds BUI's C kit for the Go binding: `go generate ./bui`
// runs it. It configures CMake once in .bui/build with the C compiler cgo uses
// (`go env CC`, so the libraries link with it: MinGW gcc on Windows), builds
// bui_kit, and copies the static libraries to .bui/lib and the public headers to
// .bui/include, where package bui's #cgo lines look. Files are copied only when
// their content changed, and bui/kit_hash.go names the libraries' content, so
// a new kit rebuilds and relinks the package (Go does not hash the libraries
// #cgo LDFLAGS names) while an unchanged one rebuilds nothing.
//
// BUI_SOURCE_DIR builds another BUI checkout; BUI_CMAKE_GENERATOR picks another
// CMake generator (Ninja is used when it is on PATH).
//
// SPDX-License-Identifier: GPL-2.0-or-later
package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
)

func main() {
	if err := build(); err != nil {
		fmt.Fprintln(os.Stderr, "kitgen:", err)
		os.Exit(1)
	}
}

func build() error {
	module, err := moduleDir()
	if err != nil {
		return err
	}
	root := os.Getenv("BUI_SOURCE_DIR")
	if root == "" {
		root = filepath.Join(module, "..", "..")
	}
	if _, err := os.Stat(filepath.Join(root, "kit", "include", "BUI_kit.h")); err != nil {
		return fmt.Errorf("BUI source tree not found at %q (set BUI_SOURCE_DIR)", root)
	}
	out := filepath.Join(module, ".bui")
	dir := filepath.Join(out, "build")
	if !configuredFor(dir, root) {
		// a cache for another source tree: CMake refuses it, so start afresh
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		if err := configure(root, dir); err != nil {
			return err
		}
	}
	if err := run("cmake", "--build", dir, "--config", "Release", "--target", "bui_kit"); err != nil {
		return err
	}
	sum := sha256.New()
	for _, lib := range []string{"kit", "gpu", "core"} {
		name := "libbui_" + lib + ".a"
		src := filepath.Join(dir, lib, name)
		if _, err := os.Stat(src); err != nil {
			src = filepath.Join(dir, lib, "Release", name)
		}
		data, err := copyIfChanged(src, filepath.Join(out, "lib", name))
		if err != nil {
			return err
		}
		sum.Write(data)
	}
	stamp := fmt.Sprintf(`// Code generated by kitgen; DO NOT EDIT.

package bui

// kitHash names the kit libraries this package links: a new kit changes it,
// so Go rebuilds and relinks the package.
const kitHash = "%x"
`, sum.Sum(nil))
	if err := writeIfChanged(filepath.Join(module, "bui", "kit_hash.go"), []byte(stamp)); err != nil {
		return err
	}
	for _, inc := range []string{"kit/include", "gpu/include"} {
		headers, _ := filepath.Glob(filepath.Join(root, inc, "*.h"))
		for _, h := range headers {
			if _, err := copyIfChanged(h, filepath.Join(out, "include", filepath.Base(h))); err != nil {
				return err
			}
		}
	}
	return nil
}

// configure runs CMake with cgo's compiler, Release, and only the kit.
func configure(root, dir string) error {
	cc := goEnv("CC")
	if cc == "" {
		cc = "gcc"
	}
	cxx := goEnv("CXX")
	if cxx == "" {
		cxx = "g++"
		if strings.Contains(cc, "clang") {
			cxx = "clang++"
		}
	}
	args := []string{"-S", root, "-B", dir, "-DCMAKE_BUILD_TYPE=Release"}
	for _, c := range []struct{ lang, cmd string }{{"C", cc}, {"CXX", cxx}} {
		words := splitQuoted(c.cmd)
		if len(words) == 0 {
			return fmt.Errorf("empty %s compiler", c.lang)
		}
		// a launcher in front of the compiler ("ccache gcc") goes to CMake apart
		if len(words) > 1 && launchers[strings.TrimSuffix(strings.ToLower(filepath.Base(words[0])), ".exe")] {
			args = append(args, "-DCMAKE_"+c.lang+"_COMPILER_LAUNCHER="+words[0])
			words = words[1:]
		}
		// the compiler and its arguments ("gcc -m32"), as CMake's list
		args = append(args, "-DCMAKE_"+c.lang+"_COMPILER="+strings.Join(words, ";"))
	}
	args = append(args,
		"-DBUI_BUILD_TESTS=OFF",
		"-DBUI_BUILD_EXAMPLES=OFF",
		"-DBUI_BUILD_PYTHON_BINDINGS=OFF",
		"-DBUI_BUILD_LUA_BINDINGS=OFF",
		"-DBUI_BUILD_QT_BACKEND=OFF",
		"-DBUI_BUILD_IMGUI=OFF",
	)
	gen := os.Getenv("BUI_CMAKE_GENERATOR")
	if gen == "" {
		if _, err := exec.LookPath("ninja"); err == nil {
			gen = "Ninja"
		} else if runtime.GOOS == "windows" {
			gen = "MinGW Makefiles"
		}
	}
	if gen != "" {
		args = append(args, "-G", gen)
	}
	return run("cmake", args...)
}

// launchers are the compiler launchers CC and CXX can start with.
var launchers = map[string]bool{"ccache": true, "sccache": true, "kache": true, "distcc": true, "icecc": true}

// splitQuoted splits a command as go env prints CC: on spaces, with single or
// double quotes around words holding spaces.
func splitQuoted(s string) []string {
	var words []string
	var w strings.Builder
	quote, in := rune(0), false
	for _, r := range s {
		switch {
		case quote != 0 && r == quote:
			quote = 0
		case quote == 0 && (r == '"' || r == '\''):
			quote, in = r, true
		case quote == 0 && (r == ' ' || r == '\t'):
			if in {
				words = append(words, w.String())
				w.Reset()
				in = false
			}
		default:
			w.WriteRune(r)
			in = true
		}
	}
	if in {
		words = append(words, w.String())
	}
	return words
}

// configuredFor reports whether dir holds a CMake cache made for root.
func configuredFor(dir, root string) bool {
	data, err := os.ReadFile(filepath.Join(dir, "CMakeCache.txt"))
	if err != nil {
		return false
	}
	const key = "CMAKE_HOME_DIRECTORY:INTERNAL="
	i := bytes.Index(data, []byte(key))
	if i < 0 {
		return false
	}
	line := data[i+len(key):]
	if j := bytes.IndexByte(line, '\n'); j >= 0 {
		line = line[:j]
	}
	abs, err := filepath.Abs(root)
	if err != nil {
		return false
	}
	have, want := filepath.Clean(strings.TrimSpace(string(line))), filepath.Clean(abs)
	if runtime.GOOS == "windows" {
		return strings.EqualFold(have, want)
	}
	return have == want
}

// moduleDir is the directory holding go.mod, from the working directory up
// (go generate runs in the package's directory).
func moduleDir() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above the working directory")
		}
		dir = parent
	}
}

func goEnv(key string) string {
	out, err := exec.Command("go", "env", key).Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(out))
}

func run(name string, args ...string) error {
	cmd := exec.Command(name, args...)
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	return nil
}

// copyIfChanged copies src to dst unless dst holds the same, and returns the
// content.
func copyIfChanged(src, dst string) ([]byte, error) {
	data, err := os.ReadFile(src)
	if err != nil {
		return nil, err
	}
	return data, writeIfChanged(dst, data)
}

// writeIfChanged writes data to dst unless dst holds it already: an unchanged
// file keeps its time, and Go's cache stays valid.
func writeIfChanged(dst string, data []byte) error {
	if old, err := os.ReadFile(dst); err == nil && bytes.Equal(old, data) {
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o644)
}
